#!/usr/bin/env python3
"""Duplicate-dependency ratchet for the root workspace.

A *duplicate group* is one crate name resolved in more than one version in the
same build graph. Duplicates are not automatically wrong (a transitive
dependency may not have upgraded yet), but a new group is a supply-chain event:
it doubles the audit surface, the binary size and the number of semver
contracts a consumer inherits. The gate therefore pins the current set in
`scripts/dependency-duplicates.baseline.txt` and only fails when a group is
*added*:

* a group that is not in the baseline -> exit 1, every group is printed;
* a baseline group that is no longer duplicated -> exit 0, with a hint to
  tighten the baseline (the ratchet never loosens by itself);
* a version change inside a known group -> exit 0 (routine dependency bumps
  must not require a baseline edit), reported as `~ name: a,b -> c,d`.

The graph is read from `cargo metadata --locked`, which resolves the same
package set as `cargo tree --workspace -d` but is host-independent: it includes
every target/platform dependency (Windows, macOS, Linux) instead of only the
dependencies of the machine the check runs on. One baseline therefore works on
the ubuntu CI runner and on a developer's workstation. `cargo tree -d` also
prints a single-version package once per dependency kind it is reached through
(and twice more when those paths are split), so its group count is larger than
the number of genuinely duplicated crates.

Usage (from the repository root, or from anywhere):

    python3 scripts/check-dependency-dedup.py            # gate
    python3 scripts/check-dependency-dedup.py --update   # rewrite the baseline

Exit codes: 0 = no new duplicate group, 1 = new duplicate group(s),
2 = the workspace could not be resolved (for example a stale Cargo.lock).
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "scripts" / "dependency-duplicates.baseline.txt"

BASELINE_HEADER = """\
# Duplicate dependency versions in the root workspace.
#
# Generated by `python3 scripts/check-dependency-dedup.py --update`; do not
# hand-edit. One line per crate that resolves in more than one version:
#
#     name@version,version[,...]
#
# The CI gate (`Dependencies (duplicate versions)`) fails when a group appears
# that is not listed here and never fails on the reverse: a group that
# collapses to one version is reported as "can tighten the baseline".
# Versions inside a group are informational; only the crate name is compared.
"""


def version_key(version):
    """Sort key that keeps 0.9.x below 0.10.x and ignores a pre-release tail."""
    head, _, tail = version.partition("-")
    parts = []
    for component in head.split("."):
        digits = component.split("+")[0]
        parts.append((0, int(digits), "") if digits.isdigit() else (1, 0, component))
    return (parts, tail)


def load_graph():
    """Return {crate: sorted versions} for every duplicated crate."""
    try:
        result = subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        print("error: cargo is not on PATH", file=sys.stderr)
        sys.exit(2)
    if result.returncode != 0:
        print("error: `cargo metadata --locked` failed:", file=sys.stderr)
        print(result.stderr.rstrip(), file=sys.stderr)
        sys.exit(2)
    metadata = json.loads(result.stdout)
    versions = {}
    for package in metadata["packages"]:
        versions.setdefault(package["name"], set()).add(package["version"])
    return {
        name: sorted(package_versions, key=version_key)
        for name, package_versions in versions.items()
        if len(package_versions) > 1
    }


def load_baseline():
    if not BASELINE.exists():
        print(f"error: missing baseline {BASELINE}", file=sys.stderr)
        print("run `python3 scripts/check-dependency-dedup.py --update`", file=sys.stderr)
        sys.exit(2)
    baseline = {}
    for number, raw in enumerate(BASELINE.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        name, separator, versions = line.partition("@")
        if not separator or not name.strip() or not versions.strip():
            print(f"error: {BASELINE}:{number}: expected `name@version,...`, got {raw!r}", file=sys.stderr)
            sys.exit(2)
        baseline[name.strip()] = [version.strip() for version in versions.split(",")]
    return baseline


def render(groups):
    lines = [f"{name}@{','.join(versions)}" for name, versions in sorted(groups.items())]
    return BASELINE_HEADER + "\n".join(lines) + "\n"


def main(argv):
    update = "--update" in argv
    unknown = [argument for argument in argv if argument != "--update"]
    if unknown:
        print(f"error: unknown argument(s): {' '.join(unknown)}", file=sys.stderr)
        print(__doc__.split("Usage", 1)[1], file=sys.stderr)
        return 2

    current = load_graph()

    if update:
        BASELINE.write_text(render(current), encoding="utf-8")
        print(f"dependency duplicates: baseline rewritten with {len(current)} group(s)")
        for name, versions in sorted(current.items()):
            print(f"  {name}@{','.join(versions)}")
        return 0

    baseline = load_baseline()
    added = sorted(set(current) - set(baseline))
    removed = sorted(set(baseline) - set(current))
    drifted = [name for name in sorted(set(current) & set(baseline)) if current[name] != baseline[name]]

    print(f"dependency duplicates: {len(current)} group(s) resolved, {len(baseline)} in the baseline")

    if added:
        print("")
        print("new duplicate group(s) - pick one version or allowlist the split:")
        for name in added:
            print(f"  + {name}@{','.join(current[name])}")
        print("")
        print("`cargo tree -d -i <crate>@<version>` shows who pulls the extra version.")
        print("If the split is deliberate, run `--update` and explain why in the PR.")
        return 1

    if removed:
        print("")
        print("duplicate group(s) gone - run `--update` to tighten the baseline:")
        for name in removed:
            print(f"  - {name}@{','.join(baseline[name])}")

    for name in drifted:
        print(f"  ~ {name}: {','.join(baseline[name])} -> {','.join(current[name])}")

    print("OK: no new duplicate dependency group")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
