#!/usr/bin/env python3
"""Generate the published-crate inventory from Cargo metadata.

The inventory is a single Markdown include consumed by
docs/rust-webx/04-architecture/crate-layout.md. Package name, import name,
publish status and Cargo description all come from the workspace manifest, so a
crate rename/addition/removal cannot silently drift in the handbook.

Usage:
    python scripts/gen-crate-inventory.py          # write the include
    python scripts/gen-crate-inventory.py --check  # fail if it is stale
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "rust-webx" / "04-architecture" / "crate-inventory.inc"

GROUP_ORDER = [
    "核心运行时",
    "扩展能力",
    "AI 领域",
    "认证",
    "缓存/实时",
    "事件传输",
    "支付",
    "传输",
    "移动推送",
    "构建期",
]

DIRECT_GROUPS = {
    "core": "核心运行时",
    "host": "核心运行时",
    "engine": "核心运行时",
    "macros": "核心运行时",
    "webx": "核心运行时",
    "spa": "扩展能力",
    "openapi": "扩展能力",
    "client": "扩展能力",
    "outbox": "扩展能力",
    "build": "构建期",
}
NESTED_GROUPS = {
    "ai": "AI 领域",
    "auth": "认证",
    "cache": "缓存/实时",
    "queue": "事件传输",
    "payment": "支付",
    "transport": "传输",
    "push": "移动推送",
}


def group_for(manifest: Path) -> str:
    rel = manifest.relative_to(ROOT / "crates")
    parts = rel.parts
    if len(parts) == 2:  # crates/<name>/Cargo.toml
        return DIRECT_GROUPS.get(parts[0], "其他")
    if len(parts) == 3:  # crates/<group>/<name>/Cargo.toml
        return NESTED_GROUPS.get(parts[0], "其他")
    return "其他"


def md_cell(text: str) -> str:
    text = " ".join(text.split())
    return text.replace("|", "\\|")


def collect() -> list[dict]:
    raw = subprocess.check_output(
        ["cargo", "metadata", "--no-deps", "--format-version", "1"],
        cwd=ROOT,
        text=True,
        encoding="utf-8",
    )
    metadata = json.loads(raw)
    workspace_root = Path(metadata["workspace_root"]).resolve()
    crates = []
    for pkg in metadata["packages"]:
        name = pkg["name"]
        if not name.startswith("rust-webx"):
            continue
        # cargo metadata: publish == [] means publish = false; null = allowed.
        if pkg.get("publish") == []:
            continue
        lib = next(
            (t["name"] for t in pkg["targets"] if "lib" in t["kind"] or "proc-macro" in t["kind"]),
            name.replace("-", "_"),
        )
        manifest = Path(pkg["manifest_path"]).resolve()
        # Examples/testing are separate workspaces and are not workspace members; guard anyway.
        if workspace_root not in manifest.parents:
            continue
        crates.append(
            {
                "name": name,
                "lib": lib,
                "group": group_for(manifest),
                "description": pkg.get("description") or "",
            }
        )
    if not crates:
        raise SystemExit("crate inventory: no published rust-webx packages found")
    crates.sort(key=lambda c: (GROUP_ORDER.index(c["group"]) if c["group"] in GROUP_ORDER else 99, c["name"]))
    return crates


def render(crates: list[dict]) -> str:
    lines = [
        "<!-- AUTO-GENERATED by scripts/gen-crate-inventory.py from `cargo metadata`; DO NOT EDIT. -->",
        "",
        f"共 {len(crates)} 个已发布 crate（`publish = false` 的 examples/testing 不在内）：",
        "",
        "| 分组 | 包名（`Cargo.toml`） | 导入名（`use`） | 职责（Cargo description） |",
        "|---|---|---|---|",
    ]
    for crate in crates:
        lines.append(
            f"| {crate['group']} | `{crate['name']}` | `{crate['lib']}` | "
            f"{md_cell(crate['description'])} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv[1:]
    expected = render(collect())
    if check:
        actual = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if actual != expected:
            print(
                "crate inventory is stale: run `python scripts/gen-crate-inventory.py`",
                file=sys.stderr,
            )
            return 1
        print(f"crate inventory: ok ({len(collect())} published crates)")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(collect())} published crates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
