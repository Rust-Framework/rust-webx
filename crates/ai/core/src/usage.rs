//! Usage metering and token accounting.
//!
//! A gateway bills per token, not per request, so every completed (or aborted)
//! stream must produce exactly one [`UsageEvent`]. The event carries the
//! provider-reported token counts when available; [`ITokenizer`] is the
//! fallback for upstreams that omit usage and for pre-flight estimates.
//!
//! The types here are deliberately transport- and provider-neutral:
//!
//! * no OpenAI/Anthropic field names;
//! * cost is integer micro-USD (`u64`), never a float;
//! * `request_id` is the idempotency key — a sink must upsert on it;
//! * a sink stamps `created_at_unix_secs` when the caller leaves it `0`.
//!
//! [`IUsageSink`] is the write port; [`MemoryUsageSink`] is a single-process
//! implementation for tests and small deployments. A database/outbox sink
//! implements the same port. [`rollup_events`] is a pure function for windowed
//! reporting, so no aggregation logic has to live in the write path.

use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, HashMap};
use std::sync::Mutex;
use std::time::{SystemTime, UNIX_EPOCH};
use thiserror::Error;

/// Token usage for one request.
///
/// `cached_tokens` and `reasoning_tokens` are subsets the provider reports
/// separately (prompt caching, reasoning models): they are already included in
/// `prompt_tokens` / `completion_tokens` respectively. [`Usage::total_tokens`]
/// therefore counts `prompt + completion` only, matching the OpenAI wire
/// definition and the billable semantics in `cost.rs`. Adding the subsets
/// again would double-count them and over-charge quota/billing.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Usage {
    /// Input tokens billed for the request.
    #[serde(default)]
    pub prompt_tokens: u64,
    /// Output tokens generated by the model.
    #[serde(default)]
    pub completion_tokens: u64,
    /// Prompt tokens served from a provider-side cache, when reported.
    #[serde(default)]
    pub cached_tokens: u64,
    /// Reasoning tokens reported separately by reasoning models.
    #[serde(default)]
    pub reasoning_tokens: u64,
}

impl Usage {
    /// No tokens (used for requests that failed before producing output).
    pub const ZERO: Self = Self {
        prompt_tokens: 0,
        completion_tokens: 0,
        cached_tokens: 0,
        reasoning_tokens: 0,
    };

    /// Prompt + completion tokens; the common two-bucket case.
    pub const fn new(prompt_tokens: u64, completion_tokens: u64) -> Self {
        Self {
            prompt_tokens,
            completion_tokens,
            cached_tokens: 0,
            reasoning_tokens: 0,
        }
    }

    /// Billable total: prompt + completion tokens, saturating instead of
    /// wrapping. `cached_tokens` and `reasoning_tokens` are reported subsets
    /// already contained in those two buckets and are intentionally not added
    /// again (see the struct docs and `cost::cost_micros`).
    pub fn total_tokens(&self) -> u64 {
        self.prompt_tokens.saturating_add(self.completion_tokens)
    }

    /// Sum of all four reported buckets. Only for telemetry that deliberately
    /// wants raw provider counters; never use for billing or quota.
    pub fn sum_all_buckets(&self) -> u64 {
        self.prompt_tokens
            .saturating_add(self.completion_tokens)
            .saturating_add(self.cached_tokens)
            .saturating_add(self.reasoning_tokens)
    }

    /// Whether every bucket is zero.
    pub fn is_empty(&self) -> bool {
        self.total_tokens() == 0
    }
}

impl std::ops::AddAssign for Usage {
    fn add_assign(&mut self, other: Self) {
        self.prompt_tokens = self.prompt_tokens.saturating_add(other.prompt_tokens);
        self.completion_tokens = self
            .completion_tokens
            .saturating_add(other.completion_tokens);
        self.cached_tokens = self.cached_tokens.saturating_add(other.cached_tokens);
        self.reasoning_tokens = self.reasoning_tokens.saturating_add(other.reasoning_tokens);
    }
}

/// How a request ended, from the usage ledger's point of view.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum UsageStatus {
    /// The upstream stream ended normally.
    Completed,
    /// The client disconnected before the stream completed; usage is estimated.
    ClientGone,
    /// The upstream failed after the gateway had started forwarding.
    UpstreamError,
}

/// One append-only usage record.
///
/// `request_id` is unique: a sink must be idempotent on it so a retried
/// settlement never double-bills.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UsageEvent {
    /// Gateway request id, also the idempotency key.
    pub request_id: String,
    /// Tenant that owns the API key.
    pub tenant_id: String,
    /// API key id (never the key itself).
    pub key_id: String,
    /// Public model/alias the client asked for.
    pub model: String,
    /// Upstream provider that served the request.
    pub provider: String,
    /// Token usage for the request.
    #[serde(default)]
    pub usage: Usage,
    /// Cost in integer micro-USD (1 USD = 1_000_000).
    pub cost_micros: u64,
    /// End-to-end latency in milliseconds.
    pub latency_ms: u32,
    /// Time to first token in milliseconds, for streamed requests.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ttft_ms: Option<u32>,
    /// How the request ended.
    pub status: UsageStatus,
    /// Event creation time in Unix seconds. A sink stamps it when `0`.
    #[serde(default)]
    pub created_at_unix_secs: u64,
}

impl UsageEvent {
    /// A record with zero cost/latency and no TTFT; add them with the builders.
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        request_id: impl Into<String>,
        tenant_id: impl Into<String>,
        key_id: impl Into<String>,
        model: impl Into<String>,
        provider: impl Into<String>,
        usage: Usage,
        status: UsageStatus,
    ) -> Self {
        Self {
            request_id: request_id.into(),
            tenant_id: tenant_id.into(),
            key_id: key_id.into(),
            model: model.into(),
            provider: provider.into(),
            usage,
            cost_micros: 0,
            latency_ms: 0,
            ttft_ms: None,
            status,
            created_at_unix_secs: 0,
        }
    }

    /// Set the cost in micro-USD.
    pub fn with_cost(mut self, cost_micros: u64) -> Self {
        self.cost_micros = cost_micros;
        self
    }

    /// Set the end-to-end latency.
    pub fn with_latency(mut self, latency_ms: u32) -> Self {
        self.latency_ms = latency_ms;
        self
    }

    /// Set the time to first token.
    pub fn with_ttft(mut self, ttft_ms: u32) -> Self {
        self.ttft_ms = Some(ttft_ms);
        self
    }

    /// Set the event timestamp (Unix seconds).
    pub fn with_timestamp(mut self, created_at_unix_secs: u64) -> Self {
        self.created_at_unix_secs = created_at_unix_secs;
        self
    }
}

/// Token counter for pre-flight estimates and for upstreams that omit usage.
///
/// Implementations are provider/model specific (a `tiktoken` table, a vendor
/// tokenizer, or a conservative byte heuristic). Counting is synchronous
/// because it is CPU work over an in-memory prompt, not I/O.
pub trait ITokenizer: Send + Sync {
    /// Estimate the number of tokens in `text` for `model`.
    fn count(&self, model: &str, text: &str) -> usize;
}

/// Byte-based token estimate.
///
/// This is a **fallback**, not an accurate tokenizer: English text averages
/// roughly 4 bytes per token, while CJK/emoji differ substantially. Use a real
/// tokenizer table when pricing precision matters; use this when the upstream
/// omitted usage and an order-of-magnitude estimate is enough.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HeuristicTokenizer {
    bytes_per_token: usize,
}

impl HeuristicTokenizer {
    /// Use `bytes_per_token` bytes per estimated token (clamped to at least 1).
    pub fn new(bytes_per_token: usize) -> Self {
        Self {
            bytes_per_token: bytes_per_token.max(1),
        }
    }
}

impl Default for HeuristicTokenizer {
    fn default() -> Self {
        Self::new(4)
    }
}

impl ITokenizer for HeuristicTokenizer {
    fn count(&self, _model: &str, text: &str) -> usize {
        if text.is_empty() {
            0
        } else {
            text.len().div_ceil(self.bytes_per_token)
        }
    }
}

/// Why a usage record could not be stored.
#[derive(Debug, Error)]
pub enum UsageError {
    /// The sink is temporarily unavailable (network/database).
    #[error("usage sink unavailable: {0}")]
    Unavailable(String),
    /// The event is not valid (for example an empty request id).
    #[error("invalid usage event: {0}")]
    Invalid(String),
}

impl UsageError {
    /// Suggested HTTP status: `503` for an unavailable sink, `400` for an
    /// invalid event.
    pub fn http_status(&self) -> u16 {
        match self {
            Self::Unavailable(_) => 503,
            Self::Invalid(_) => 400,
        }
    }
}

/// Idempotent usage write port.
///
/// Implementations upsert by [`UsageEvent::request_id`] and ignore a duplicate
/// write (first write wins); a retried settlement must be harmless.
#[async_trait]
pub trait IUsageSink: Send + Sync {
    /// Persist one event; duplicate `request_id` is a no-op.
    async fn record(&self, event: UsageEvent) -> Result<(), UsageError>;
}

/// Single-process sink for tests and small deployments.
///
/// It stamps `created_at_unix_secs` when the caller leaves it `0`, and keeps the
/// first event for each request id (idempotent upsert-ignore).
#[derive(Default)]
pub struct MemoryUsageSink {
    events: Mutex<HashMap<String, UsageEvent>>,
}

impl MemoryUsageSink {
    /// An empty sink.
    pub fn new() -> Self {
        Self::default()
    }

    /// Number of stored events.
    pub fn len(&self) -> usize {
        self.lock().len()
    }

    /// Whether no event has been stored.
    pub fn is_empty(&self) -> bool {
        self.lock().is_empty()
    }

    /// Fetch one event by request id.
    pub fn get(&self, request_id: &str) -> Option<UsageEvent> {
        self.lock().get(request_id).cloned()
    }

    /// All stored events, ordered by request id.
    pub fn snapshot(&self) -> Vec<UsageEvent> {
        let events = self.lock();
        let mut values: Vec<_> = events.values().cloned().collect();
        values.sort_by(|left, right| left.request_id.cmp(&right.request_id));
        values
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, HashMap<String, UsageEvent>> {
        self.events
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }
}

#[async_trait]
impl IUsageSink for MemoryUsageSink {
    async fn record(&self, mut event: UsageEvent) -> Result<(), UsageError> {
        if event.request_id.trim().is_empty() {
            return Err(UsageError::Invalid("request_id must not be empty".into()));
        }
        if event.created_at_unix_secs == 0 {
            event.created_at_unix_secs = unix_secs();
        }
        self.lock().entry(event.request_id.clone()).or_insert(event);
        Ok(())
    }
}

/// One aggregated window of usage, grouped by tenant + model.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UsageRollup {
    /// Inclusive start of the window, Unix seconds.
    pub window_start_unix_secs: u64,
    /// Tenant the events belong to.
    pub tenant_id: String,
    /// Public model/alias.
    pub model: String,
    /// Number of events in the window.
    pub requests: u64,
    /// Summed token usage.
    pub usage: Usage,
    /// Summed cost in micro-USD.
    pub cost_micros: u64,
}

impl UsageRollup {
    /// Fold one event into this window.
    pub fn accumulate(&mut self, event: &UsageEvent) {
        self.requests = self.requests.saturating_add(1);
        self.usage += event.usage;
        self.cost_micros = self.cost_micros.saturating_add(event.cost_micros);
    }
}

/// Aggregate `events` into fixed windows of `window_secs`, grouped by tenant and
/// model.
///
/// Pure and deterministic: the caller owns the clock. Events with
/// `created_at_unix_secs == 0` land in window `0`, so stamp timestamps before
/// rolling up (a sink does this).
pub fn rollup_events<I>(events: I, window_secs: u64) -> Vec<UsageRollup>
where
    I: IntoIterator<Item = UsageEvent>,
{
    let window_secs = window_secs.max(1);
    let mut windows: BTreeMap<(u64, String, String), UsageRollup> = BTreeMap::new();

    for event in events {
        let window_start = (event.created_at_unix_secs / window_secs) * window_secs;
        let key = (window_start, event.tenant_id.clone(), event.model.clone());
        let rollup = windows.entry(key).or_insert_with(|| UsageRollup {
            window_start_unix_secs: window_start,
            tenant_id: event.tenant_id.clone(),
            model: event.model.clone(),
            requests: 0,
            usage: Usage::ZERO,
            cost_micros: 0,
        });
        rollup.accumulate(&event);
    }

    windows.into_values().collect()
}

fn unix_secs() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|elapsed| elapsed.as_secs())
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn event(request_id: &str, tenant: &str, model: &str, at: u64) -> UsageEvent {
        UsageEvent::new(
            request_id,
            tenant,
            "key-1",
            model,
            "openai",
            Usage::new(10, 20),
            UsageStatus::Completed,
        )
        .with_timestamp(at)
        .with_cost(100)
    }

    #[test]
    fn default_usage_is_zero_and_empty() {
        let usage = Usage::default();
        assert_eq!(usage, Usage::ZERO);
        assert_eq!(usage.total_tokens(), 0);
        assert!(usage.is_empty());
    }

    #[test]
    fn total_tokens_counts_subsets_once() {
        let usage = Usage {
            prompt_tokens: 10,
            completion_tokens: 20,
            cached_tokens: 3,
            reasoning_tokens: 5,
        };
        assert_eq!(
            usage.total_tokens(),
            30,
            "subsets must not be double-counted"
        );
        assert_eq!(usage.sum_all_buckets(), 38);
        assert!(!usage.is_empty());
    }

    #[test]
    fn total_tokens_saturates_instead_of_wrapping() {
        let usage = Usage {
            prompt_tokens: u64::MAX,
            completion_tokens: 1,
            ..Usage::default()
        };
        assert_eq!(usage.total_tokens(), u64::MAX);
    }

    #[test]
    fn add_assign_sums_every_bucket() {
        let mut left = Usage::new(1, 2);
        left.cached_tokens = 3;
        left.reasoning_tokens = 4;
        left += Usage::new(10, 20);
        assert_eq!(
            left,
            Usage {
                prompt_tokens: 11,
                completion_tokens: 22,
                cached_tokens: 3,
                reasoning_tokens: 4,
            }
        );
    }

    #[test]
    fn usage_event_omits_ttft_when_absent_and_round_trips() {
        let event = UsageEvent {
            request_id: "req-1".into(),
            tenant_id: "tenant-1".into(),
            key_id: "key-1".into(),
            model: "fast".into(),
            provider: "openai".into(),
            usage: Usage::new(12, 34),
            cost_micros: 56,
            latency_ms: 789,
            ttft_ms: None,
            status: UsageStatus::Completed,
            created_at_unix_secs: 0,
        };

        let value = serde_json::to_value(&event).expect("event serializes");
        assert_eq!(value["status"], json!("completed"));
        assert!(
            value.get("ttft_ms").is_none(),
            "an absent ttft must not serialize as null"
        );

        let decoded: UsageEvent = serde_json::from_value(value).expect("event deserializes");
        assert_eq!(decoded, event);
    }

    #[test]
    fn usage_statuses_use_snake_case_on_the_wire() {
        let cases = [
            (UsageStatus::Completed, "completed"),
            (UsageStatus::ClientGone, "client_gone"),
            (UsageStatus::UpstreamError, "upstream_error"),
        ];
        for (status, expected) in cases {
            assert_eq!(
                serde_json::to_value(status).expect("status serializes"),
                json!(expected)
            );
        }
    }

    #[test]
    fn heuristic_tokenizer_counts_bytes_and_handles_empty() {
        let tokenizer = HeuristicTokenizer::default();
        assert_eq!(tokenizer.count("any", ""), 0);
        assert_eq!(tokenizer.count("any", "abcd"), 1);
        assert_eq!(tokenizer.count("any", "abcde"), 2);
        assert_eq!(HeuristicTokenizer::new(0).count("any", "a"), 1);

        let fine = HeuristicTokenizer::new(2);
        assert_eq!(fine.count("any", "abcd"), 2);
    }

    #[tokio::test]
    async fn memory_sink_stamps_and_is_idempotent() {
        let sink = MemoryUsageSink::new();
        sink.record(event("req-1", "tenant-1", "fast", 0))
            .await
            .expect("first write");

        let stored = sink.get("req-1").expect("event stored");
        assert!(stored.created_at_unix_secs > 0, "sink must stamp time");

        let duplicate = event("req-1", "tenant-1", "fast", 1).with_cost(999);
        sink.record(duplicate).await.expect("duplicate is ignored");
        assert_eq!(sink.len(), 1);
        assert_eq!(sink.get("req-1").expect("still stored").cost_micros, 100);
    }

    #[tokio::test]
    async fn memory_sink_rejects_an_empty_request_id() {
        let sink = MemoryUsageSink::new();
        let error = sink
            .record(event("", "tenant-1", "fast", 1))
            .await
            .expect_err("empty id is invalid");
        assert!(matches!(error, UsageError::Invalid(_)));
        assert_eq!(error.http_status(), 400);
        assert_eq!(sink.len(), 0);
    }

    #[test]
    fn rollup_groups_by_window_tenant_and_model() {
        let events = vec![
            event("a", "tenant-1", "fast", 10),
            event("b", "tenant-1", "fast", 20),
            event("c", "tenant-1", "smart", 25),
            event("d", "tenant-2", "fast", 30),
            event("e", "tenant-1", "fast", 70),
        ];

        let rollups = rollup_events(events, 60);
        assert_eq!(rollups.len(), 4);

        let first = &rollups[0];
        assert_eq!(first.window_start_unix_secs, 0);
        assert_eq!(first.tenant_id, "tenant-1");
        assert_eq!(first.model, "fast");
        assert_eq!(first.requests, 2);
        assert_eq!(first.usage.total_tokens(), 60);
        assert_eq!(first.cost_micros, 200);

        let last = rollups.last().expect("last window");
        assert_eq!(last.window_start_unix_secs, 60);
        assert_eq!(last.requests, 1);
    }

    #[test]
    fn rollup_treats_a_zero_window_as_one_second() {
        let rollups = rollup_events(vec![event("a", "t", "m", 5)], 0);
        assert_eq!(rollups[0].window_start_unix_secs, 5);
    }
}
