//! Endpoint —IEndpoint implementations for dual-mode dispatch.

use serde_json;
use std::sync::Arc;
use webx_core::error::Result;
use webx_core::http::IHttpContext;
use webx_core::routing::IEndpoint;

use crate::authz::AuthorizerSet;
use crate::problem_response::{write_forbidden, write_problem};
use std::collections::HashMap;
use webx_spa::SpaMiddleware;

/// Endpoint that wraps a boxed async handler.
#[allow(clippy::type_complexity)]
pub struct RequestEndpoint {
    handler: Box<
        dyn Fn(
                &mut dyn IHttpContext,
            )
                -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<()>> + Send + '_>>
            + Send
            + Sync,
    >,
}

#[async_trait::async_trait]
impl IEndpoint for RequestEndpoint {
    async fn handle(&self, ctx: &mut dyn IHttpContext) -> Result<()> {
        (self.handler)(ctx).await
    }
}

impl RequestEndpoint {
    pub fn new<F>(f: F) -> Self
    where
        F: for<'a> Fn(
                &'a mut dyn IHttpContext,
            ) -> std::pin::Pin<
                Box<dyn std::future::Future<Output = Result<()>> + Send + 'a>,
            > + Send
            + Sync
            + 'static,
    {
        Self {
            handler: Box::new(f),
        }
    }
}

/// A route endpoint that dispatches to the registered handler via cache.
///
/// When a dispatch function is available (generated by the endpoint macros),
/// it constructs the request from the live HTTP context, calls the handler
/// via the HandlerCache call bridge, and writes the response.
/// Falls back to a descriptive stub message when no dispatch function is registered.
pub struct StubEndpoint {
    pub method: &'static str,
    pub path: &'static str,
    pub handler_type: &'static str,
    pub dispatch_fn: Option<webx_core::route::scan::RouteDispatchFn>,
    /// Rules collected from `#[authorize]`; empty means the endpoint is public.
    /// Every rule must be satisfied (statically, or by the dynamic authorizers
    /// when [`Self::authorization_dynamic`] is `true`).
    pub authorization: &'static [webx_core::route::scan::AuthorizeRule],
    /// `true` when the endpoint declared `#[authorize(dynamic)]`.
    ///
    /// The static gate then only requires an authenticated principal (no claims
    /// → 401) and [`Self::authorization`] is handed to the dynamic authorizers,
    /// which decide. `false` — the default for every other route — means the
    /// claim snapshot must satisfy the rules before dispatch.
    pub authorization_dynamic: bool,
    /// Dynamic authorizers (from `IDynamicAuthorizer` DI registrations).
    /// Checked after the declarative rules (or instead of them on a dynamic
    /// endpoint) and before handler dispatch.
    /// When `None`, no dynamic authorization checks run (pass-through).
    pub authorizers: Option<Arc<AuthorizerSet>>,
    /// Per-route request body cap from `#[max_body_size(..)]`; `None` keeps the
    /// global `App.MaxBodySize`.
    pub max_body_size: Option<usize>,
}

impl StubEndpoint {
    /// Apply the route's body limit and declarative/dynamic authorization.
    ///
    /// Kept separate so the direct-dispatch target can enforce exactly the same
    /// guard without routing through the legacy dispatch closure.
    pub(crate) async fn authorize(&self, ctx: &mut dyn IHttpContext) -> Result<bool> {
        if let Some(limit) = self.max_body_size {
            ctx.request_mut().set_max_body_size(limit);
        }
        ctx.request_mut().validate_declared_body_limit()?;
        if !self.authorization.is_empty() || self.authorization_dynamic {
            if ctx.claims().is_none() {
                return Err(webx_core::error::Error::Unauthorized(
                    "authentication required".to_string(),
                ));
            }

            if !self.authorization_dynamic {
                let denied = {
                    let claims = ctx.claims().expect("claims presence is checked above");
                    self.authorization
                        .iter()
                        .find(|rule| !rule.matches(claims.roles(), claims.permissions()))
                        .map(|rule| (rule.roles, rule.permissions))
                };

                if let Some((roles, permissions)) = denied {
                    let mut ext = HashMap::new();
                    ext.insert("required_roles".into(), serde_json::json!(roles));
                    ext.insert(
                        "required_permissions".into(),
                        serde_json::json!(permissions),
                    );
                    write_forbidden(ctx, "Forbidden: insufficient permissions", ext).await;
                    return Ok(false);
                }
            }

            if self.authorization_dynamic {
                let authorizers = self
                    .authorizers
                    .as_ref()
                    .filter(|set| !set.is_empty())
                    .ok_or_else(|| {
                        webx_core::error::Error::Internal(
                            "dynamic authorization requires a registered IDynamicAuthorizer"
                                .to_string(),
                        )
                    })?;
                if let Some(claims) = ctx.claims() {
                    let resource_key = ctx.request().route_pattern().unwrap_or(self.path);
                    let method = ctx.request().method();
                    authorizers
                        .authorize_with_declared_rules(
                            claims,
                            resource_key,
                            method,
                            self.authorization,
                        )
                        .await?;
                }
            } else if let Some(authorizers) = self.authorizers.as_ref() {
                if !authorizers.is_empty() {
                    if let Some(claims) = ctx.claims() {
                        let resource_key = ctx.request().route_pattern().unwrap_or(self.path);
                        let method = ctx.request().method();
                        authorizers
                            .authorize_with_declared_rules(
                                claims,
                                resource_key,
                                method,
                                self.authorization,
                            )
                            .await?;
                    }
                }
            }
        }
        Ok(true)
    }
}

#[async_trait::async_trait]
impl IEndpoint for StubEndpoint {
    async fn handle(&self, ctx: &mut dyn IHttpContext) -> Result<()> {
        if !self.authorize(ctx).await? {
            return Ok(());
        }

        if let Some(dispatch) = self.dispatch_fn {
            let response = dispatch(&mut *ctx).await?;
            response.execute(&mut *ctx).await?;
            return Ok(());
        }

        write_problem(
            ctx,
            501,
            &format!(
                "Route handler not implemented: {} {} (request type: {})",
                self.method, self.path, self.handler_type
            ),
        )
        .await;
        Ok(())
    }
}

/// Engine-native direct target: authorization guard + compile-time dispatch,
/// without crossing the legacy `IEndpoint` trait object.
pub struct DirectRouteTarget {
    auth: Arc<StubEndpoint>,
    dispatch: webx_core::route::scan::HandlerDispatchFn,
}

impl DirectRouteTarget {
    pub fn new(
        auth: Arc<StubEndpoint>,
        dispatch: webx_core::route::scan::HandlerDispatchFn,
    ) -> Self {
        Self { auth, dispatch }
    }
}

#[async_trait::async_trait]
impl webx_engine::RouteTarget for DirectRouteTarget {
    async fn handle(&self, ctx: &mut webx_engine::EngineContext) -> Result<()> {
        if !self.auth.authorize(ctx).await? {
            return Ok(());
        }
        let result = (self.dispatch)(ctx as &mut dyn IHttpContext).await?;
        ctx.write_endpoint_result(result).await
    }
}

