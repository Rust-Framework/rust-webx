/// Endpoint that serves a static JSON payload.
///
/// Used for built-in endpoints like `/openapi.json` and `/health`.
/// The `content_type` field allows IETF API Health Check `application/health+json`
/// for health endpoints while defaulting to `application/json`.
pub struct StaticJsonEndpoint {
    pub body: Vec<u8>,
    pub content_type: &'static str,
}

impl StaticJsonEndpoint {
    /// Create a new endpoint with the default `application/json` content type.
    pub fn new(body: Vec<u8>) -> Self {
        Self {
            body,
            content_type: "application/json",
        }
    }
}

#[async_trait::async_trait]
impl IEndpoint for StaticJsonEndpoint {
    async fn handle(&self, ctx: &mut dyn IHttpContext) -> Result<()> {
        ctx.response_mut().set_status(200);
        ctx.response_mut()
            .set_header("content-type", self.content_type);
        ctx.response_mut().write_bytes(self.body.clone()).await
    }
}

/// Engine fallback for a genuine router miss.
///
/// Serves the SPA index shell when the request is an HTML navigation and a SPA
/// is configured; otherwise returns a routing error so the engine's normal
/// 404/error-writer path runs.
pub struct SpaFallbackEndpoint {
    spa: Arc<SpaMiddleware>,
}

impl SpaFallbackEndpoint {
    pub fn new(spa: Arc<SpaMiddleware>) -> Self {
        Self { spa }
    }
}

#[async_trait::async_trait]
impl IEndpoint for SpaFallbackEndpoint {
    async fn handle(&self, ctx: &mut dyn IHttpContext) -> Result<()> {
        // A middleware may already have answered (static file from SpaMiddleware
        // sets the body and lets routing continue). Keep that response instead
        // of turning it into the SPA shell or a 404.
        if ctx.response().has_body() {
            return Ok(());
        }
        if self.spa.try_index_fallback(ctx).await? {
            Ok(())
        } else {
            Err(webx_core::error::Error::route_not_found(
                "Not Found".to_string(),
            ))
        }
    }
}

/// Endpoint that serves a static HTML payload.
///
/// Used for built-in endpoints like `/api/docs`.
pub struct StaticHtmlEndpoint {
    pub body: &'static str,
}

#[async_trait::async_trait]
impl IEndpoint for StaticHtmlEndpoint {
    async fn handle(&self, ctx: &mut dyn IHttpContext) -> Result<()> {
        ctx.response_mut().set_status(200);
        ctx.response_mut()
            .set_header("content-type", "text/html; charset=utf-8");
        ctx.response_mut()
            .write_bytes(self.body.as_bytes().to_vec())
            .await
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use webx_core::action::EndpointResult;
    use webx_core::route::scan::HandlerDispatchFn;
    use webx_core::route::scan::{AuthorizeRule, DirectResponseEncoderFn};

    fn stub(
        authorization: &'static [AuthorizeRule],
        authorization_dynamic: bool,
        max_body_size: Option<usize>,
    ) -> Arc<StubEndpoint> {
        Arc::new(StubEndpoint {
            method: "GET",
            path: "/test",
            handler_type: "test::Request",
            dispatch_fn: None,
            authorization,
            authorization_dynamic,
            authorizers: None,
            max_body_size,
        })
    }

    fn dummy_dispatch<'a>(
        _ctx: &'a mut dyn IHttpContext,
        _encoder: DirectResponseEncoderFn,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<EndpointResult>> + Send + 'a>>
    {
        Box::pin(async { Ok(EndpointResult::Empty) })
    }

    fn dummy_encoder(_: &dyn std::any::Any) -> Result<EndpointResult> {
        Ok(EndpointResult::Empty)
    }

    fn target(auth: Arc<StubEndpoint>) -> DirectRouteTarget {
        let dispatch: HandlerDispatchFn = dummy_dispatch;
        DirectRouteTarget::new(auth, dispatch, dummy_encoder)
    }

    #[test]
    fn direct_fast_path_is_only_selected_for_unguarded_routes() {
        use webx_engine::RouteTarget;

        // Public, no body cap: the engine may call the dispatch function directly.
        assert!(
            target(stub(&[], false, None)).direct().is_some(),
            "unguarded route should use the direct fast path"
        );

        // Any authorization rule, dynamic authorization or route body cap means
        // the guarded `handle` path runs instead.
        const AUTHENTICATED: &[AuthorizeRule] = &[AuthorizeRule::authenticated()];
        assert!(
            target(stub(AUTHENTICATED, false, None)).direct().is_none(),
            "a route with an authorization rule must go through the guard"
        );
        assert!(
            target(stub(&[], true, None)).direct().is_none(),
            "a dynamic-authorization route must go through the guard"
        );
        assert!(
            target(stub(&[], false, Some(16))).direct().is_none(),
            "a route with a per-route body cap must go through the guard"
        );
    }
}
